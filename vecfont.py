ADVANCE = 6  # glyph width 4 + spacing 2


def strokes(text: str, size: float, x0: float = 0, y0: float = 0) -> list[list[Stroke]]:
    """Strokes per character, scaled so one grid unit is `size` px; (x0, y0) is the top-left."""
    out = []
    for i, ch in enumerate(text):
        g = GLYPHS.get(ch.upper(), [])
        ox = x0 + i * ADVANCE * size
        out.append([[(ox + x * size, y0 + y * size) for x, y in s] for s in g])
    return out


def width(text: str, size: float) -> float:
    return (len(text) * ADVANCE - 2) * size


def path_d(stroke: Stroke) -> str:
    return "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in stroke)


def length(stroke: Stroke) -> float:
    return sum(math.dist(a, b) for a, b in zip(stroke, stroke[1:]))


def sample(stroke: Stroke, step: float) -> list[Point]:
    """Evenly spaced points along a polyline (both ends included)."""
    total = length(stroke)
    if total == 0:
        return [stroke[0]]
    n = max(1, round(total / step))
    pts, seg, acc = [], 0, 0.0
    for k in range(n + 1):
        target = total * k / n
        while seg < len(stroke) - 2 and acc + math.dist(stroke[seg], stroke[seg + 1]) < target:
            acc += math.dist(stroke[seg], stroke[seg + 1])
            seg += 1
        (ax, ay), (bx, by) = stroke[seg], stroke[seg + 1]
        L = math.dist((ax, ay), (bx, by)) or 1
        t = min(1.0, (target - acc) / L)
        pts.append((ax + (bx - ax) * t, ay + (by - ay) * t))
    return pts
